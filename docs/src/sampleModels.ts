import * as THREE from 'three';

/**
 * Converts any Three.js BufferGeometry into a standard binary STL ArrayBuffer.
 */
export function geometryToSTLBuffer(geometry: THREE.BufferGeometry): ArrayBuffer {
  const nonIndexed = geometry.index ? geometry.toNonIndexed() : geometry.clone();
  nonIndexed.computeVertexNormals();

  const pos = nonIndexed.attributes.position;
  const normalAttr = nonIndexed.attributes.normal;
  const triangles = pos.count / 3;

  // Binary STL: 80 bytes header + 4 bytes triangle count + 50 bytes per triangle
  const bufferSize = 84 + triangles * 50;
  const buffer = new ArrayBuffer(bufferSize);
  const view = new DataView(buffer);

  // Write 80-byte header
  const header = 'Binary STL generated by 3D STL Studio';
  for (let i = 0; i < header.length && i < 80; i++) {
    view.setUint8(i, header.charCodeAt(i));
  }

  // Number of triangles
  view.setUint32(80, triangles, true);

  let offset = 84;
  const pA = new THREE.Vector3();
  const pB = new THREE.Vector3();
  const pC = new THREE.Vector3();
  const nA = new THREE.Vector3();
  const nB = new THREE.Vector3();
  const nC = new THREE.Vector3();
  const normal = new THREE.Vector3();

  for (let i = 0; i < pos.count; i += 3) {
    pA.fromBufferAttribute(pos, i);
    pB.fromBufferAttribute(pos, i + 1);
    pC.fromBufferAttribute(pos, i + 2);

    if (normalAttr) {
      nA.fromBufferAttribute(normalAttr, i);
      nB.fromBufferAttribute(normalAttr, i + 1);
      nC.fromBufferAttribute(normalAttr, i + 2);
      normal.copy(nA).add(nB).add(nC).divideScalar(3).normalize();
    } else {
      const cb = new THREE.Vector3().subVectors(pC, pB);
      const ab = new THREE.Vector3().subVectors(pA, pB);
      normal.crossVectors(cb, ab).normalize();
    }

    // Normal vector
    view.setFloat32(offset, normal.x, true);
    view.setFloat32(offset + 4, normal.y, true);
    view.setFloat32(offset + 8, normal.z, true);
    offset += 12;

    // Vertices pA, pB, pC
    for (const p of [pA, pB, pC]) {
      view.setFloat32(offset, p.x, true);
      view.setFloat32(offset + 4, p.y, true);
      view.setFloat32(offset + 8, p.z, true);
      offset += 12;
    }

    // Attribute byte count (uint16)
    view.setUint16(offset, 0, true);
    offset += 2;
  }

  return buffer;
}

/**
 * Generates a realistic Mechanical Spur Gear with 18 teeth and center bore
 */
export function createGearSTL(): ArrayBuffer {
  const teeth = 18;
  const outerRadius = 24;
  const pitchRadius = 20;
  const rootRadius = 16;
  const boreRadius = 6;
  const depth = 8;

  const shape = new THREE.Shape();
  const totalPoints = teeth * 4;

  for (let i = 0; i < totalPoints; i++) {
    const angle = (i / totalPoints) * Math.PI * 2;
    const toothStep = i % 4;
    let r = pitchRadius;

    if (toothStep === 0) r = rootRadius;
    else if (toothStep === 1 || toothStep === 2) r = outerRadius;
    else r = rootRadius;

    const x = Math.cos(angle) * r;
    const y = Math.sin(angle) * r;

    if (i === 0) {
      shape.moveTo(x, y);
    } else {
      shape.lineTo(x, y);
    }
  }
  shape.closePath();

  // Center axle bore hole
  const holePath = new THREE.Path();
  holePath.absarc(0, 0, boreRadius, 0, Math.PI * 2, true);
  shape.holes.push(holePath);

  // 4 Weight-reduction cutout holes in gear body
  const cutoutRadius = 3;
  const cutoutDistance = 11;
  for (let c = 0; c < 4; c++) {
    const ca = (c / 4) * Math.PI * 2;
    const cx = Math.cos(ca) * cutoutDistance;
    const cy = Math.sin(ca) * cutoutDistance;
    const cutoutHole = new THREE.Path();
    cutoutHole.absarc(cx, cy, cutoutRadius, 0, Math.PI * 2, true);
    shape.holes.push(cutoutHole);
  }

  const extrudeSettings = {
    depth,
    bevelEnabled: true,
    bevelSegments: 3,
    steps: 1,
    bevelSize: 0.8,
    bevelThickness: 0.8,
  };

  const geom = new THREE.ExtrudeGeometry(shape, extrudeSettings);
  geom.rotateX(Math.PI / 2);
  return geometryToSTLBuffer(geom);
}

/**
 * Generates a standard 20x20x20mm Calibration Cube
 */
export function createCalibrationCubeSTL(): ArrayBuffer {
  const size = 20;
  // Create rounded/beveled box by combining box with bevel or clean box geometry
  const geom = new THREE.BoxGeometry(size, size, size, 4, 4, 4);
  return geometryToSTLBuffer(geom);
}

/**
 * Generates a complex Torus Knot
 */
export function createTorusKnotSTL(): ArrayBuffer {
  const geom = new THREE.TorusKnotGeometry(14, 4.2, 128, 32, 2, 3);
  return geometryToSTLBuffer(geom);
}

/**
 * Generates a faceted Polyhedron / Crystal
 */
export function createCrystalSTL(): ArrayBuffer {
  const geom = new THREE.IcosahedronGeometry(16, 1);
  return geometryToSTLBuffer(geom);
}

